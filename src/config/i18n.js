export function configText(text, language = 'en') {
  const source = String(text ?? '');
  if (language !== 'vi') return source;
  if (VI[source]) return VI[source];
  if (source.includes(' · ')) return source.split(' · ').map((part) => VI[part] ?? part).join(' · ');
  return source;
}
